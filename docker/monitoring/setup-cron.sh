#!/usr/bin/env bash
# =============================================================================
# setup-cron.sh — cron에 모니터링 스크립트를 자동 등록하는 스크립트
# =============================================================================
#
# [파일 역할]
#   pg-healthcheck.sh와 pg-daily-report.sh를 cron에 등록하여
#   자동으로 주기적 실행되게 만든다.
#   한 번만 실행하면 되며, 재실행해도 중복 등록되지 않는다.
#
# [cron이란?]
#   리눅스의 예약 작업 스케줄러. "매 5분마다", "매일 09:00" 등
#   정해진 시간에 명령어를 자동 실행한다.
#   crontab -e 로 편집, crontab -l 로 목록 확인.
#
# [cron 시간 포맷]
#   분  시  일  월  요일  명령어
#   ─── ─── ─── ─── ────
#   */5 *   *   *   *     → 매 5분마다
#   0   9   *   *   *     → 매일 09:00
#   30  2   *   *   1     → 매주 월요일 02:30
#
# [사용법]
#   cd docker/monitoring
#   cp .env.example .env   # 먼저 .env 파일을 설정해야 한다
#   vim .env               # DISCORD_WEBHOOK_URL 등 입력
#   bash setup-cron.sh     # cron 등록
#
# =============================================================================

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# 각 스크립트의 절대 경로를 변수에 저장
HEALTHCHECK="$SCRIPT_DIR/pg-healthcheck.sh"
DAILY_REPORT="$SCRIPT_DIR/pg-daily-report.sh"

# -----------------------------------------------------------------------------
# chmod +x: 파일에 실행 권한을 부여한다.
#
# 리눅스 파일 권한 기초:
#   r (read=4)    → 읽기
#   w (write=2)   → 쓰기
#   x (execute=1) → 실행  ← 이것이 없으면 ./스크립트.sh 로 실행할 수 없다
#
# +x: 소유자/그룹/기타 모두에게 실행 권한 추가
# git clone 직후에는 실행 권한이 없을 수 있으므로 여기서 부여한다.
# -----------------------------------------------------------------------------
chmod +x "$HEALTHCHECK" "$DAILY_REPORT" "$SCRIPT_DIR/discord-webhook.sh"

# -----------------------------------------------------------------------------
# cron 등록 — 기존 항목 제거 후 재등록 (멱등성 보장)
#
# "멱등성(idempotent)": 여러 번 실행해도 결과가 같다.
# 이 스크립트를 5번 실행해도 cron에 5줄이 추가되는 게 아니라 항상 2줄만 있다.
#
# [전체 데이터 흐름]
#
#   ┌─────────────────────────────────────────────────────────┐
#   │ crontab -l                                              │
#   │ (현재 cron 목록 전체 출력)                                │
#   │ 예: "0 3 * * * /backup.sh # backup"                     │
#   │     "*/5 * * * * /path/pg-healthcheck.sh # pg-monitoring"│
#   └──────────────────┬──────────────────────────────────────┘
#                      │
#                      ▼
#   ┌─────────────────────────────────────────────────────────┐
#   │ grep -v "$CRON_MARKER"                                  │
#   │ (# pg-monitoring 이 포함된 줄을 제거)                      │
#   │ 결과: "0 3 * * * /backup.sh # backup"                   │
#   │ (기존 모니터링 항목만 제거됨, 다른 cron은 유지)              │
#   └──────────────────┬──────────────────────────────────────┘
#                      │
#                      ▼
#   ┌─────────────────────────────────────────────────────────┐
#   │ cat <<EOF ... EOF                                       │
#   │ (새 모니터링 항목 2줄을 추가)                               │
#   │ 결과:                                                    │
#   │   "0 3 * * * /backup.sh # backup"                       │
#   │   "*/5 * * * * /path/pg-healthcheck.sh ... # pg-monitoring"│
#   │   "0 9 * * * /path/pg-daily-report.sh ... # pg-monitoring" │
#   └──────────────────┬──────────────────────────────────────┘
#                      │
#                      ▼
#   ┌─────────────────────────────────────────────────────────┐
#   │ | crontab -                                             │
#   │ (파이프로 받은 내용을 새 crontab으로 설정)                   │
#   │ crontab - : stdin에서 읽어서 crontab 전체를 교체           │
#   └─────────────────────────────────────────────────────────┘
#
# 핵심 원리:
#   CRON_MARKER="# pg-monitoring" 을 각 줄 끝에 태그로 붙여서,
#   재실행 시 grep -v로 이전 항목을 정확히 식별하고 제거할 수 있다.
# -----------------------------------------------------------------------------
CRON_MARKER="# pg-monitoring"

# ( ... ) : 서브셸. 괄호 안의 명령들을 하나의 출력 스트림으로 묶는다.
# crontab -l 2>/dev/null : 현재 cron 목록 출력. 빈 경우 에러 → /dev/null로 숨김
# | grep -v "$CRON_MARKER" : 마커가 포함된 줄을 제거 (-v: 반전 매칭)
# || true : grep 결과가 0줄이어도 에러(exit 1)를 내지 않도록 방지
#           (set -e 때문에 grep 실패 시 스크립트가 중단될 수 있음)
# ; cat <<EOF ... EOF : 새로운 cron 항목 2줄을 추가
# ) | crontab - : 서브셸의 전체 출력을 crontab에 입력으로 전달
(crontab -l 2>/dev/null | grep -v "$CRON_MARKER" || true; cat <<EOF
*/5 * * * * $HEALTHCHECK >> /var/log/pg-healthcheck.log 2>&1 $CRON_MARKER
0 9 * * * $DAILY_REPORT >> /var/log/pg-daily-report.log 2>&1 $CRON_MARKER
EOF
) | crontab -
# >> : append 리다이렉트. 기존 로그 파일 내용을 유지하면서 뒤에 추가한다.
#      > (덮어쓰기)와 달리 이전 로그가 삭제되지 않는다.
# 2>&1 : stderr(파일 디스크립터 2)를 stdout(파일 디스크립터 1)과 같은 곳으로 보냄.
#        에러 메시지도 로그 파일에 기록된다.

echo "✅ cron 등록 완료:"
echo "  - 헬스체크: 5분마다"
echo "  - 일일 리포트: 매일 09:00"
echo ""
echo "확인: crontab -l"
echo "로그: tail -f /var/log/pg-healthcheck.log"
