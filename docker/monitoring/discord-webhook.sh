#!/usr/bin/env bash
# =============================================================================
# discord-webhook.sh — Discord 웹훅 전송 유틸리티
# =============================================================================
#
# [파일 역할]
#   다른 스크립트(pg-healthcheck.sh, pg-daily-report.sh)에서 Discord로 메시지를
#   보내기 위한 "공용 라이브러리" 역할을 한다.
#   이 파일 자체를 직접 실행하는 것이 아니라, 다른 스크립트에서
#   `source discord-webhook.sh` 로 불러와서 함수와 변수를 사용한다.
#
# [데이터 흐름]
#   .env 파일 → 환경변수 로드 → send_discord() 호출 시 →
#   JSON payload 생성 → curl로 Discord API에 POST → Discord 채널에 메시지 표시
#
# [사용법]
#   source discord-webhook.sh
#   send_discord "제목" "본문" "$COLOR_RED"
#
# =============================================================================

# -----------------------------------------------------------------------------
# SCRIPT_DIR: 이 스크립트 파일이 위치한 디렉토리의 절대 경로를 구한다.
#
# 분해 설명:
#   ${BASH_SOURCE[0]}  → 현재 실행(또는 source)되고 있는 파일의 경로
#                         예: ./discord-webhook.sh 또는 /home/user/monitoring/discord-webhook.sh
#   dirname "..."      → 경로에서 파일명을 제거하고 디렉토리 부분만 추출
#                         예: /home/user/monitoring/discord-webhook.sh → /home/user/monitoring
#   cd "..." && pwd    → 해당 디렉토리로 이동 후 절대 경로를 출력
#                         이렇게 하면 상대 경로(./monitoring)도 절대 경로로 변환된다
#   $( ... )           → 명령어 치환. 괄호 안의 명령 결과를 문자열로 반환한다
#
# 왜 필요한가?
#   cron에서 실행될 때는 현재 디렉토리가 / 일 수 있어서,
#   스크립트 기준 상대 경로로 .env 파일 등을 찾으려면 절대 경로가 필요하다.
# -----------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# -----------------------------------------------------------------------------
# .env 파일에서 환경변수를 로드한다.
#
# 분해 설명:
#   [[ -f "$SCRIPT_DIR/.env" ]]  → .env 파일이 존재하는지 확인 (-f: 일반 파일인지)
#   grep -v '^#'                 → '#'으로 시작하는 주석 줄을 제외 (-v: 매칭 반전)
#   xargs                        → 여러 줄을 한 줄의 인자로 변환
#                                  예: "A=1\nB=2" → "A=1 B=2"
#   export $(...)                → 변환된 KEY=VALUE 쌍들을 환경변수로 등록
#
# .env 파일 예시:
#   DISCORD_WEBHOOK_URL=https://discord.com/api/webhooks/...
#   PG_HOST=localhost
#
# 로드 후:
#   $DISCORD_WEBHOOK_URL, $PG_HOST 등을 스크립트 내에서 사용 가능
# -----------------------------------------------------------------------------
if [[ -f "$SCRIPT_DIR/.env" ]]; then
    export $(grep -v '^#' "$SCRIPT_DIR/.env" | xargs)
fi

# -----------------------------------------------------------------------------
# DISCORD_WEBHOOK_URL이 비어 있으면 경고를 출력한다.
#
#   [[ -z "$변수" ]]  → 변수가 빈 문자열인지 확인 (-z: zero length)
#   반대: [[ -n "$변수" ]]  → 비어있지 않은지 확인 (-n: non-zero length)
# -----------------------------------------------------------------------------
if [[ -z "$DISCORD_WEBHOOK_URL" ]]; then
    echo "[WARN] DISCORD_WEBHOOK_URL이 설정되지 않았습니다. .env 파일을 확인하세요."
fi

# -----------------------------------------------------------------------------
# Discord embed에서 사용하는 색상 코드 (10진수 정수).
# Discord API는 색상을 10진수 integer로 받는다.
#
# 변환 예: 초록색 #2ECC71 → 16진수 0x2ECC71 → 10진수 3066993
#
# 이 변수들은 전역 변수로, source한 다른 스크립트에서도 접근 가능하다.
# -----------------------------------------------------------------------------
COLOR_GREEN=3066993    # 정상 (초록)
COLOR_YELLOW=16776960  # 경고 (노란)
COLOR_RED=15158332     # 위험 (빨강)

# =============================================================================
# send_discord() — Discord 웹훅으로 embed 메시지를 전송하는 함수
# =============================================================================
#
# [매개변수]
#   $1 → title       : embed 제목 (예: "🔴 PostgreSQL Alert")
#   $2 → description : embed 본문 (여러 줄 가능, \n으로 줄바꿈)
#   $3 → color       : 색상 코드 (생략 시 기본값 COLOR_GREEN)
#   $4 → footer      : 하단 텍스트 (생략 시 "호스트명 • 현재시각" 자동 생성)
#
# [데이터 흐름]
#   매개변수 → json_escape()로 특수문자 처리 → JSON payload 조립 →
#   curl로 Discord Webhook URL에 POST 전송 → HTTP 상태 코드 반환
#
# [반환값]
#   curl의 stdout으로 HTTP 상태 코드가 출력된다 (예: 204 = 성공)
#
send_discord() {
    # -------------------------------------------------------------------------
    # local: 함수 내부에서만 유효한 지역 변수를 선언한다.
    #        local 없이 선언하면 전역 변수가 되어 다른 함수에 영향을 줄 수 있다.
    #
    # ${3:-$COLOR_GREEN}: 파라미터 기본값 문법
    #   → $3이 비어있거나 미전달이면 $COLOR_GREEN을 사용한다.
    #   비슷한 문법:
    #     ${변수:-기본값}  → 변수가 비어있으면 기본값 사용 (변수 자체는 안 바뀜)
    #     ${변수:=기본값}  → 변수가 비어있으면 기본값으로 대입까지 수행
    # -------------------------------------------------------------------------
    local title="$1"
    local description="$2"
    local color="${3:-$COLOR_GREEN}"
    local footer="${4:-$(hostname) • $(date '+%Y-%m-%d %H:%M:%S %Z')}"
    #                    ^^^^^^^^                 ^^^^
    #                    서버 호스트명 출력        현재 날짜/시간 포맷팅
    #                    예: "prod-db-01"         예: "2025-01-15 03:24:11 KST"

    # -------------------------------------------------------------------------
    # 웹훅 URL이 없으면 Discord 전송을 건너뛰고 콘솔에만 출력한다.
    # return 0: 함수를 정상 종료한다 (0 = 성공 코드).
    # -------------------------------------------------------------------------
    if [[ -z "$DISCORD_WEBHOOK_URL" ]]; then
        echo "[SKIP] Discord 웹훅 URL 미설정 — 콘솔 출력만 합니다."
        echo "=== $title ==="
        echo "$description"
        return 0
    fi

    # -------------------------------------------------------------------------
    # Heredoc(히어독)으로 JSON payload를 생성한다.
    #
    # 문법: 변수=$(cat <<구분자
    #         여러 줄 내용 ...
    #       구분자
    #       )
    #
    # cat <<PAYLOAD ... PAYLOAD
    #   → PAYLOAD라는 구분자 사이의 텍스트를 cat에 입력으로 전달한다.
    #   → 내부의 $변수는 실제 값으로 치환된다.
    #   → 치환을 막으려면 <<'PAYLOAD' (따옴표)로 쓴다.
    #
    # json_escape()를 호출하여 제목/본문에 있는 큰따옴표, 줄바꿈 등
    # JSON에서 문제되는 문자를 이스케이프 처리한다.
    # -------------------------------------------------------------------------
    local payload
    payload=$(cat <<PAYLOAD
{
  "embeds": [{
    "title": $(json_escape "$title"),
    "description": $(json_escape "$description"),
    "color": $color,
    "footer": {
      "text": $(json_escape "$footer")
    }
  }]
}
PAYLOAD
)

    # -------------------------------------------------------------------------
    # curl로 Discord Webhook API에 POST 요청을 보낸다.
    #
    # 옵션 설명:
    #   -s              → silent 모드. 진행률 표시 숨김.
    #   -o /dev/null    → 응답 본문(body)을 버린다 (/dev/null = 리눅스 쓰레기통)
    #   -w "%{http_code}" → 응답의 HTTP 상태 코드만 stdout에 출력
    #                       예: 204 (성공), 400 (잘못된 요청), 429 (속도 제한)
    #   -H "..."        → HTTP 헤더 지정 (JSON 형식으로 보낸다고 선언)
    #   -d "$payload"   → POST 요청의 body 데이터
    #
    # \(백슬래시): 줄 끝에서 사용하면 다음 줄과 이어서 하나의 명령으로 해석.
    #             긴 명령어를 보기 좋게 여러 줄로 나눌 때 사용한다.
    # -------------------------------------------------------------------------
    curl -s -o /dev/null -w "%{http_code}" \
        -H "Content-Type: application/json" \
        -d "$payload" \
        "$DISCORD_WEBHOOK_URL"
}

# =============================================================================
# json_escape() — 문자열을 JSON 안전한 형태로 이스케이프한다
# =============================================================================
#
# [왜 필요한가]
#   Discord로 보내는 메시지에 큰따옴표("), 줄바꿈(\n), 역슬래시(\) 등이
#   포함되면 JSON 구조가 깨진다. 이 함수가 그런 문자를 안전하게 변환한다.
#
# [입력]  $1 → 원본 문자열 (예: 'hello "world"')
# [출력]  JSON 이스케이프된 문자열 (예: '"hello \"world\""')
#
# [동작 방식]
#   1차 시도: python3의 json.dumps()를 사용 (가장 정확)
#   2차 시도: python3이 없으면 sed로 수동 치환 (|| 뒤의 대체 명령)
#
json_escape() {
    # -------------------------------------------------------------------------
    # python3 -c "코드"  → 파이썬 코드를 한 줄로 실행
    # sys.argv[1]        → 쉘에서 전달한 $1 인자를 파이썬에서 받는다
    # json.dumps(...)    → 파이썬 내장: 문자열을 JSON 안전하게 변환
    #                      큰따옴표 포함, 특수문자 이스케이프 처리됨
    #
    # 2>/dev/null        → stderr(에러 출력)를 버린다
    #                      python3이 없을 때 에러 메시지가 표시되지 않게 함
    #
    # || (OR 연산자)     → 왼쪽 명령이 실패하면(exit code != 0) 오른쪽을 실행
    #                      python3이 없는 환경에서의 대비책(fallback)
    #
    # printf '"%s"'      → 문자열을 큰따옴표로 감싸서 출력
    #                      %s는 문자열 자리표시자
    #
    # sed 's/A/B/g'      → 문자열 치환 (s=substitute, g=global 모든 매칭)
    #   s/\\/\\\\/g      → \ 를 \\ 로 치환 (역슬래시 이스케이프)
    #   s/"/\\"/g        → " 를 \" 로 치환 (큰따옴표 이스케이프)
    #   s/\n/\\n/g       → 줄바꿈을 \n 텍스트로 치환
    # -------------------------------------------------------------------------
    python3 -c "import json,sys; print(json.dumps(sys.argv[1]))" "$1" 2>/dev/null \
        || printf '"%s"' "$(echo "$1" | sed 's/\\/\\\\/g; s/"/\\"/g; s/\n/\\n/g')"
}
